#!/usr/bin/env python3
"""Generates the open vocabulary types (R-ENUMS-1) from conformance/vocab.json.

    python3 scripts/generate_vocab.py

Writes src/main/java/me/finlight/client/<Type>.java and <Type>Values.java. The test
VocabularyTest (kit case V-01) checks the result against vocab.json on every build.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "main", "java", "me", "finlight", "client")
vocab = json.load(open(os.path.join(ROOT, "conformance", "vocab.json")))

TYPES = [
    ("IncludeBlock", vocab["request"]["include"]["values"], "A block that {@code include} adds to an article.", {}),
    ("OrderBy", vocab["request"]["orderBy"]["values"], "The timestamp a search sorts and filters on.", {}),
    ("SortOrder", vocab["request"]["order"]["values"], "Sort direction of a search.", {}),
    ("CompanyRole", vocab["response"]["roles"]["values"], "The position of a company in the story.", {}),
    ("EventType", vocab["response"]["eventTypes"]["values"], "Type of a tagged event.", {}),
    ("EventDirection", vocab["response"]["eventDirections"]["values"], "Direction of a tagged event.", {}),
    ("Importance", vocab["response"]["importance"]["values"], "Importance of a tagged event, from low to critical.", {}),
    ("SentimentLabel", vocab["response"]["sentimentLabels"]["values"], "Sentiment label of an article.", {}),
    ("SourceType", vocab["response"]["sourceTypes"]["values"], "Type of a source, also a value of {@code sourceTypes} and {@code excludeSourceTypes}.", {}),
    ("StreamEventName", vocab["websocket"]["events"]["values"], "Name of a WebSocket frame ({@code event}).",
     {"ARTICLE_EVENTS": vocab["websocket"]["articleEvents"]["values"],
      "CONNECTION_EVENTS": vocab["websocket"]["connectionEvents"]["values"]}),
    ("ConnectionErrorCode", vocab["websocket"]["connectionErrorCodes"]["values"], "Code of a {@code connection.error} frame.", {}),
    ("PreemptReason", vocab["websocket"]["preemptReasons"]["values"], "Reason of a {@code connection.preempted} frame.", {}),
    ("WebhookEventName", vocab["webhook"]["events"]["values"], "Name of a webhook event.", {}),
    ("ProblemCode", [p["code"] for p in vocab["problemCodes"]["values"]], "Problem {@code code} of an API error.", {}),
    ("RateLimitType", vocab["limitTypes"]["values"] + ["unknown"],
     "Kind of a 429 limit. {@code unknown} means the answer did not say.", {}),
    ("ReconnectReason", ["rotation", "watchdog", "closed", "handshake_failed", "search_failed", "dial_failed",
                         "dial_refused", "connection_limit", "rate_limited", "quota_exceeded"],
     "Why a stream opened a new connection.", {}),
]


def const(v):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", v)
    s = re.sub(r"[^A-Za-z0-9]+", "_", s)
    return s.upper().strip("_")


HEADER = "// Generated by scripts/generate_vocab.py from conformance/vocab.json; do not edit.\n"

for name, values, doc, subsets in TYPES:
    consts = [(const(v), v) for v in values]
    lines = [HEADER, "package me.finlight.client;", "", "import java.util.List;", "",
             "/**", f" * String constants of {{@link {name}}}, usable in {{@code switch}}.", " */",
             f"public final class {name}Values {{"]
    for c, v in consts:
        lines.append(f"  /** {{@code {v}}} */")
        lines.append(f'  public static final String {c} = "{v}";')
        lines.append("")
    all_list = ", ".join(c for c, _ in consts)
    lines.append("  /** Every value this SDK version knows, in the order of the contract. */")
    lines.append(f"  public static final List<String> ALL = List.of({all_list});")
    for sub, sv in subsets.items():
        lines.append("")
        lines.append(f"  /** The subset {{@code {sub}}} of the contract. */")
        lines.append(f"  public static final List<String> {sub} = List.of({', '.join(const(v) for v in sv)});")
    lines += ["", f"  private {name}Values() {{}}", "}", ""]
    open(os.path.join(OUT, f"{name}Values.java"), "w").write("\n".join(lines))

    body = [HEADER, "package me.finlight.client;", "", "import java.util.Objects;", "import org.jspecify.annotations.Nullable;", "",
            "/**", f" * {doc}", " *",
            " * <p>Open vocabulary (R-ENUMS-1): a string plus constants for the values known today. Values this",
            " * version does not know are kept as sent. Compare with {@link #equals} or by {@link #value()}.",
            " */",
            f"public final class {name} {{"]
    for c, v in consts:
        body.append(f"  /** {{@code {v}}} */")
        body.append(f"  public static final {name} {c} = new {name}({name}Values.{c});")
        body.append("")
    body += [
        "  private final String value;", "",
        f"  private {name}(String value) {{", "    this.value = value;", "  }", "",
        "  /** Returns the constant for a known value, or a new instance that keeps {@code value} as sent. */",
        f"  public static {name} of(String value) {{",
        '    Objects.requireNonNull(value, "value");',
        "    switch (value) {",
    ]
    for c, v in consts:
        body.append(f"      case {name}Values.{c}:")
        body.append(f"        return {c};")
    body += [
        "      default:",
        f"        return new {name}(value);",
        "    }", "  }", "",
        "  /** The value as sent on the wire. */",
        "  public String value() {", "    return value;", "  }", "",
        "  /** True when this SDK version knows the value. */",
        "  public boolean isKnown() {",
        f"    return {name}Values.ALL.contains(value);", "  }", "",
        "  @Override", "  public boolean equals(@Nullable Object other) {",
        f"    return other instanceof {name} o && o.value.equals(value);", "  }", "",
        "  @Override", "  public int hashCode() {", "    return value.hashCode();", "  }", "",
        "  @Override", "  public String toString() {", "    return value;", "  }", "}", ""]
    open(os.path.join(OUT, f"{name}.java"), "w").write("\n".join(body))
print("generated", len(TYPES), "vocabularies")
